/**
 * Builds the pool of daily-challenge courses. Each candidate seed is turned into a course (district, speed, length
 * and difficulty all follow from the seed) and played through by the hold/release autopilot with 100 ms decisions;
 * only seeds it can finish are kept. The result is written to src/game/levels/daily-seeds.ts together with the
 * physics fingerprint, so the pool is flagged stale if the handling or rules ever change.
 *
 *   npm run levels:daily-seeds           400 seeds (about 10 minutes)
 *   npm run levels:daily-seeds -- 50     a smaller pool, for trying things out
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { physicsHash } from '../../src/game/levels/fingerprint';
import { createDailyWorld, specFromSeed } from '../../src/game/levels/modes';
import { SIM_HZ } from '../../src/game/physics/constants';
import { Rng } from '../../src/game/physics/rng';
import { Autopilot } from '../../src/game/systems/autopilot';

export function finishable(seed: number): boolean {
  const { world } = createDailyWorld(specFromSeed('2000-01-01', seed));
  const bot = new Autopilot(world);
  for (let t = 0; t < SIM_HZ * 150 && world.running; t++) {
    world.step({ hold: bot.decide(), steer: 0, boost: false });
    world.events.length = 0;
  }
  return world.status === 'finished';
}

function main(): void {
  const wanted = Number(process.argv[2] ?? 400);
  const rng = new Rng(20261104);
  const kept: number[] = [];
  let tried = 0;
  while (kept.length < wanted) {
    const seed = rng.int(1, 2 ** 30);
    tried += 1;
    if (!kept.includes(seed) && finishable(seed)) kept.push(seed);
    if (tried % 25 === 0) console.log(`  ${kept.length}/${wanted} kept after ${tried} tried`);
  }
  const rows = Array.from({ length: Math.ceil(kept.length / 8) }, (_, i) => kept.slice(i * 8, i * 8 + 8).join(', '));
  const lines = rows.map((row) => `  ${row},`).join('\n');
  const body = `/** Generated by \`npm run levels:daily-seeds\`. Do not edit by hand. */\n` +
    `export const DAILY_SEEDS_PHYSICS = '${physicsHash()}';\nexport const DAILY_SEEDS: readonly number[] = [\n${lines}\n];\n`;
  const file = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..', 'src', 'game', 'levels', 'daily-seeds.ts');
  writeFileSync(file, body);
  console.log(`Kept ${kept.length} of ${tried} candidate seeds (${Math.round((kept.length / tried) * 100)}% finishable).`);
}

if (process.argv[1]?.endsWith('daily-seeds.ts')) main();
