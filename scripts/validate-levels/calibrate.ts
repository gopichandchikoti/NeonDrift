/**
 * Runs the look-ahead autopilot (hold/release only, the same input a player has) over every stage and stores what it
 * achieved in src/game/levels/calibration.ts: score, time, drift points, combo, sparks, traffic passed, and its input
 * recording. Objective targets and star thresholds are derived from this, and `levels:check` replays the recording to
 * prove every stage can be finished and its objective met.
 *
 *   npm run levels:calibrate            all stages
 *   npm run levels:calibrate -- 1-03    only the stage ids given (merged into the existing file)
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CALIBRATION } from '../../src/game/levels/calibration';
import { stageHash } from '../../src/game/levels/fingerprint';
import { createStageWorld, encodeInput } from '../../src/game/levels/runner';
import { STAGE_DEFS } from '../../src/game/levels/stages';
import type { Calibration, StageDef } from '../../src/game/levels/types';
import { Autopilot, DEFAULT_WEIGHTS, type BotWeights } from '../../src/game/systems/autopilot';
import { SIM_HZ } from '../../src/game/physics/constants';

const MAX_TICKS = SIM_HZ * 240;

/** Weightings to try for a stage: one tuned to its objective first, then safer ones. The best finisher wins. */
export function candidateWeights(def: StageDef): BotWeights[] {
  const safe = { ...DEFAULT_WEIGHTS, edge: 900 };
  switch (def.objective.kind) {
    case 'sparks':
      return [{ ...DEFAULT_WEIGHTS, sparks: 220 }, { ...safe, sparks: 120 }, DEFAULT_WEIGHTS];
    case 'drift':
    case 'combo':
      return [{ ...DEFAULT_WEIGHTS, score: 0.3 }, { ...safe, score: 0.15 }, DEFAULT_WEIGHTS, safe];
    case 'time':
      return [{ ...DEFAULT_WEIGHTS, score: 0.01 }, { ...safe, score: 0.01 }];
    default:
      return [DEFAULT_WEIGHTS, safe];
  }
}

export interface BotRun {
  status: string;
  calibration: Calibration | null;
  at: number;
  cpuMs: number;
}

function runWith(def: StageDef, weights: BotWeights, every: number): BotRun {
  const world = createStageWorld(def);
  const bot = new Autopilot(world, weights, 240, every);
  const holds: boolean[] = [];
  const started = performance.now();
  while (world.running && world.tick < MAX_TICKS) {
    const hold = bot.decide();
    holds.push(hold);
    world.step({ hold, steer: 0, boost: false });
    world.events.length = 0;
  }
  const cpuMs = performance.now() - started;
  if (world.status !== 'finished') return { status: world.status, calibration: null, at: world.s, cpuMs };
  const stats = world.stats;
  const calibration: Calibration = {
    score: stats.score,
    ticks: stats.finishTicks ?? world.tick,
    driftPoints: stats.driftPoints,
    peakCombo: stats.peakCombo,
    sparks: stats.sparks,
    trafficPassed: stats.trafficPassed,
    input: encodeInput(holds),
    hash: stageHash(def),
  };
  return { status: 'finished', calibration, at: world.s, cpuMs };
}

/** How good a finished run is for this stage's objective (higher is better). */
function merit(def: StageDef, c: Calibration): number {
  switch (def.objective.kind) {
    case 'drift':
      return c.driftPoints;
    case 'combo':
      return c.peakCombo * 100000 + c.score;
    case 'sparks':
      return c.sparks;
    case 'traffic':
      return c.trafficPassed * 100000 + c.score;
    case 'time':
      return -c.ticks;
    default:
      return c.score;
  }
}

/** Decision intervals to try, slowest (most human-like) first: 12 ticks = 100 ms, 6 ticks = 50 ms. */
export const DECISION_TICKS = [12, 10, 8, 6, 4];

export function runBot(def: StageDef): BotRun {
  let cpuMs = 0;
  let last: BotRun | null = null;
  for (const every of DECISION_TICKS) {
    let best: BotRun | null = null;
    for (const weights of candidateWeights(def)) {
      const run = runWith(def, weights, every);
      cpuMs += run.cpuMs;
      last = run;
      if (!run.calibration) continue;
      if (!best?.calibration || merit(def, run.calibration) > merit(def, best.calibration)) best = run;
    }
    if (best) return { ...best, cpuMs };
  }
  return { ...(last as BotRun), cpuMs };
}

/** The shortest hold or release in a recording, in milliseconds (the first release run is the start-up delay). */
export function shortestPressMs(input: readonly number[]): number {
  return Math.round((Math.min(...input.slice(1, -1)) * 1000) / SIM_HZ);
}

function render(table: Record<string, Calibration>): string {
  const body = Object.keys(table)
    .sort()
    .map((id) => `  '${id}': ${JSON.stringify(table[id])},`)
    .join('\n');
  return `import type { Calibration } from './types';\n\n/** Generated by \`npm run levels:calibrate\`. Do not edit by hand. */\nexport const CALIBRATION: Record<string, Calibration> = {\n${body}\n};\n`;
}

function main(): void {
  const only = process.argv.slice(2);
  const defs = only.length > 0 ? STAGE_DEFS.filter((d) => only.includes(d.id)) : STAGE_DEFS;
  const table: Record<string, Calibration> = only.length > 0 ? { ...CALIBRATION } : {};
  let failures = 0;
  for (const def of defs) {
    const run = runBot(def);
    if (run.calibration) {
      table[def.id] = run.calibration;
      const c = run.calibration;
      console.log(
        `${def.id} ${def.name.padEnd(18)} ok   ${(c.ticks / SIM_HZ).toFixed(1).padStart(5)}s score ${String(c.score).padStart(6)}` +
          ` drift ${String(c.driftPoints).padStart(5)} combo x${c.peakCombo} sparks ${String(c.sparks).padStart(3)}` +
          ` traffic ${c.trafficPassed} press>=${shortestPressMs(c.input)}ms (${Math.round(run.cpuMs)} ms)`,
      );
    } else {
      failures += 1;
      console.log(`${def.id} ${def.name.padEnd(18)} FAIL ${run.status} at s=${Math.round(run.at)}`);
    }
  }
  const file = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..', 'src', 'game', 'levels', 'calibration.ts');
  writeFileSync(file, render(table));
  console.log(`\n${defs.length - failures}/${defs.length} stages calibrated${failures ? `, ${failures} FAILED` : ''}.`);
  process.exit(failures ? 1 : 0);
}

main();
