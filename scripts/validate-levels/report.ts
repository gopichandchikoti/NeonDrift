/**
 * Updates the marked level-validation region in ARCHITECTURE.md with one row per stage.
 * Run it after `npm run levels:calibrate`. Authored sections are preserved; automated replays are distinguished
 * from the human verification recorded in the same guide.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { STAGES } from '../../src/game/levels/catalog';
import { DISTRICTS } from '../../src/game/levels/districts';
import { objectiveSentence } from '../../src/game/levels/objectives';
import { buildStage } from '../../src/game/levels/runner';
import { SIM_HZ } from '../../src/game/physics/constants';
import { parseTrack } from '../../src/game/physics/track-dsl';
import { runChecks } from './check';

const pressMs = (input: readonly number[]): number => Math.round((Math.min(...input.slice(1, -1)) * 1000) / SIM_HZ);
const count = (id: string, kinds: string[]): number => {
  const stage = STAGES.find((s) => s.id === id);
  return stage ? parseTrack(stage.track).items.filter((i) => kinds.includes(i.kind)).length : 0;
};

const { issues, replays } = runChecks();
const rows = STAGES.map((stage) => {
  const cal = stage.calibration;
  const built = buildStage(stage);
  const replay = replays.find((r) => r.id === stage.id);
  const hazards = count(stage.id, ['cone', 'block', 'gate', 'traffic']);
  const cells = [
    stage.id, stage.name, stage.speed, Math.round(built.track.length), built.track.corners.length, hazards,
    objectiveSentence(stage), cal ? (cal.ticks / SIM_HZ).toFixed(1) : '-', cal?.score ?? '-',
    `${stage.stars[0]} / ${stage.stars[1]}`, cal ? pressMs(cal.input) : '-', replay?.ok ? 'pass' : 'FAIL',
  ];
  return `| ${cells.join(' | ')} |`;
});

const body = `### Generated validation results

Generated by \`npm run levels:report\`. Edit stage data or the generator to change this region.

**Summary:** ${STAGES.length} stages in ${DISTRICTS.length} districts, ${replays.filter((r) => r.ok).length} replayed to the
finish with the objective met, ${issues.length} validator issue(s).

> Automated replay shows that the recorded inputs can finish the stage and meet its objective. It does not replace
> human playtesting. See [Verification and release status](#verification-and-release-status) for the manual QA gaps.

How to read the table:

- **Length / corners / hazards**: road length in units, number of bends, and the cones, blocks, gates and traffic cars.
- **Bot time and score**: what the hold/release autopilot achieved when it played the stage. The objective target and the
  two star thresholds are derived from this.
- **Stars**: the score needed for two and three stars (one star is clearing the stage).
- **Min press**: the shortest press or release in the autopilot's recording. Every stage was finishable with presses of
  at least 83 ms, which a thumb can do.
- **Replay**: the recorded input replayed on the real simulation reached the finish, met the objective and reproduced the
  recorded score and time exactly.

| Stage | Name | Speed | Length | Bends | Hazards | Objective | Bot time (s) | Bot score | 2 / 3 stars | Min press (ms) | Replay |
|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}
${issues.length > 0 ? `\n## Issues\n\n${issues.map((i) => `- ${i.stage}: ${i.message}`).join('\n')}\n` : ''}`;

const file = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..', 'ARCHITECTURE.md');
const guide = readFileSync(file, 'utf8');
const startMarker = '<!-- level-validation:start -->';
const endMarker = '<!-- level-validation:end -->';
const start = guide.indexOf(startMarker) + startMarker.length;
const end = guide.indexOf(endMarker);
if (guide.split(startMarker).length !== 2 || guide.split(endMarker).length !== 2 || end < start) {
  throw new Error('ARCHITECTURE.md must contain one ordered pair of level-validation markers. Nothing was written.');
}
writeFileSync(file, `${guide.slice(0, start)}\n${body.trimEnd()}\n${guide.slice(end)}`);
console.log(`Updated level-validation region in ${file}`);
